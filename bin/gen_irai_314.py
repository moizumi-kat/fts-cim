def narabe(mono, haba=6, ji='     '):
    r = []
    for i in range(0, len(mono), haba):
        r.append(ji + '  '.join('%-10s' % y for y in mono[i:i + haba]).rstrip())
    return '\n'.join(r)

def keitou(mono, n=12, ji='     ', haba=70):
    """系統の内訳。cp932 で haba バイトに収まるよう折り返す。"""
    c = collections.Counter(re.match(r'^([A-Z]+)', x).group(1) for x in mono)
    tama = ['%s系 %d本' % (a, b) for a, b in c.most_common(n)]
    gyo, ima = [], ji + '系統 … '
    for t in tama:
        tasu = (ima.rstrip().endswith('…') and t) or ('／' + t)
        if len((ima + tasu).encode('cp932')) > haba and ima.strip() not in ('系統 …',):
            gyo.append(ima.rstrip('／')); ima = ji + '       ' + t
        else:
            ima += tasu
    gyo.append(ima.rstrip('／'))
    return '\n'.join(gyo)


def _sb(s):
    """製番。紙の 6-11071 → ファイルの 611071。"""
    return str(s).replace('-', '').strip()

def _dt(s, nen=None):
    """日付。紙の 26.12.20 → ファイルの 20261220。
       月日だけの 9.24 は、年を nen（既定 2026）で補う。
       0. 0. 0（未定）は 0。"""
    if s in (None, ''): return None
    t = [x.strip() for x in str(s).split('.')]
    if not all(x.isdigit() for x in t): return None
    t = [int(x) for x in t]
    if len(t) == 3:
        y, m, d = t
        if y == 0 and m == 0 and d == 0: return 0
        y = 2000 + y if y < 100 else y
    elif len(t) == 2:
        y, (m, d) = (nen or 2026), t
    else:
        return None
    return y * 10000 + m * 100 + d

def _hi(day, nen=2026):
    """日報内訳の発行日。紙には日だけが出ている（例 24）。
       対象期間が 9月21日〜10月20日なので、21日以降は9月、20日以前は10月。
       ※ この読み替えは村上様のご確認待ち。"""
    if day in (None, ''): return None
    d = int(str(day).strip())
    return (nen * 10000 + 900 + d) if d >= 21 else (nen * 10000 + 1000 + d)


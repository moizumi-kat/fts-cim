def _col(tbl, j):
    """現行の日本語項目名 → 現行の英名の列名。

    列名は英名（村上様ご指示）だが、ここは現物の紙と見くらべやすいよう
    日本語の項目名で書いている。その読み替えをここで1回だけ行う。
    繰返し項目は「受注金額(1)」のように回数まで書く。回数を省いたときは
    1回目に入れる（合計すると現物の金額に一致する）。
    """
    m = {}
    for name, ty, jname, pic in TABLES[tbl]['cols']:
        if jname: m.setdefault(jname, name)
        m.setdefault(name, name)          # 英名で書いてもよい（日本語名が無い表がある）
    return m.get(j) or m.get(j + '(1)')

_TY = {}
def _fit(tbl, col, v):
    """定義体の桁に収まるかを確かめる。収まらなければその場で止める。

    SQLite は桁あふれを黙って受けるが、SQL Server は
    「String or binary data would be truncated」で止まる。
    手元では気づけないので、投入時に必ず見る。
    char/varchar はバイト数（全角1文字＝2バイト）、
    nchar/nvarchar は文字数で数える。
    """
    if v is None: return
    key = (tbl, col)
    if key not in _TY:
        _TY[key] = dict((c[0], c[1]) for c in TABLES[tbl]['cols']).get(col, '')
    ty = _TY[key]
    m = re.match(r'^(n?)(?:char|varchar)\((\d+)\)$', ty)
    if m:
        wide, n = m.group(1) == 'n', int(m.group(2))
        v = str(v)
        size = len(v) if wide else len(v.encode('cp932', 'replace'))
        if size > n:
            raise ValueError(
                '%s.%s（%s）は %s ですが、入れようとした値が %d %s あります: %r\n'
                '      現行の桁に収まりません。現物の紙の値をそのまま入れていないか'
                'ご確認ください。' %
                (tbl, col, _JA.get((tbl, col), ''), ty, size,
                 '文字' if wide else 'バイト', v))
        return
    m = re.match(r'^(?:decimal|numeric)\((\d+),\s*(\d+)\)$', ty)
    if m:
        p, sc = int(m.group(1)), int(m.group(2))
        if isinstance(v, str):
            raise ValueError(
                '%s.%s（%s）は %s（数値）ですが、文字列 %r を入れようとしました。\n'
                '      紙の表示形式のままになっていないかご確認ください。' %
                (tbl, col, _JA.get((tbl, col), ''), ty, v))
        if len(str(abs(int(v)))) > p - sc:
            raise ValueError('%s.%s は %s ですが、整数部が多すぎます: %r'
                             % (tbl, col, ty, v))

_JA = {}
def _build_ja():
    for t in TABLES:
        for name, ty, ja, pic in TABLES[t]['cols']:
            _JA[(t, name)] = ja
_build_ja()

def _ins(con, tbl, d):
    """その表に実在する列だけを入れる（現行に無い項目を勝手に足さない）。

    現物の紙に出ていない項目は None で渡している。レプリケーション対象の表は
    定義体どおり NOT NULL ＋ 既定値つきなので、None の項目は**入れずに飛ばし**、
    現行と同じ既定値（0 や空白）が入るようにする。
    """
    nn = set(TABLES[tbl].get('notnull') or [])
    dd = {}
    for k, v in d.items():
        c = _col(tbl, k)
        if not c: continue
        if v is None and c in nn: continue     # 既定値にまかせる
        _fit(tbl, c, v)
        dd[c] = v
    if not dd: return
    con.execute('INSERT INTO %s(%s) VALUES(%s)'
                % (tbl, ','.join(Q(k) for k in dd), ','.join('?' * len(dd))),
                tuple(dd.values()))


# ---------------------------------------------------------------- 現物の紙 → 現行ファイルの形
# 紙に出ているのは「人が読む形」です。現行ファイルが持っているのは別の形なので、
# ここで現行の形に直してから入れます。直しかたは現行の COBOL で裏を取りました。
#
#   製番   紙 6-11071（7文字） → ファイル 611071（X(06)）
#          B10100PP.COB が 製番(1:1)＋"-"＋製番(2:5) で印字している。
#   日付   紙 26.12.20 → ファイル 20261220（9(08)）
#          B10100PP.COB が 9(08) の下6桁だけを印字している。

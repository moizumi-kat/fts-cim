# -*- coding: utf-8 -*-
"""`止まったところ.txt` を、人に見せる形にまとめ直す。

     python3 点検/tomatta_matome.py [出力先.txt]

茂泉様のご指示「問題があれば、提示してもらい、一緒につぶしていきましょう」
（2026-11-20）のための道具。

■ 分け方
  区分ごとにまとめ、**「こちらで直します」「問題ではありません」**と
  **「ご確認いただきたいこと」**をはっきり分ける。
  人に判断してもらう必要があるものだけを探せるようにするため。
"""
import sys, pathlib, re, collections, datetime

ここ = pathlib.Path(__file__).resolve().parent.parent
MOTO = ここ / '止まったところ.txt'
SAKI = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 \
    else ここ / '止まったところ_ご確認用.txt'

SETSU = {
    'ア　ＧＯ ＴＯ の飛び先が節の外': [
        'ＣＯＢＯＬ は節をまたいで ＧＯ ＴＯ できます。写し方を直します。',
        '→ こちらで直します。ご判断は不要です。'],
    'イ　ＲＥＡＤ の先が見つからない': [
        '作業ファイル（ＣＬが実行前に作るもの）か、まだ手元に無いファイルです。',
        '→ こちらで一時ファイルとして用意します。'],
    'ウ　書き先が見つからない': [
        'プログラム間の受け渡し用レコードです。イと同じ扱いになります。'],
    'エ　【ご確認】定義体の無いファイルの中身が分からない': [
        'ＣＯＢＯＬ が `COPY ○○ OF XFDLIB` でレコードの中身を書いていて、',
        'その**コピー原文が手元にありません**。どの桁が何の項目かを',
        '決められないため、ここで止まります。',
        '→ ご確認のお願い【２】です。コピー原文をいただければ動きます。'],
    'オ　ＰＥＲＦＯＲＭ 〜 ＴＨＲＵ 〜 の飛び先が無い': [
        '飛び先の段落・節が、その原文の中に見当たりません。',
        '→ まず原文を読み直します。'],
    'カ　【ご確認】外部プログラム ＸＳＢＳＳＩ': [
        'ＸＳＢＳＳＩ の原文が手元にありません。',
        '→ ご確認のお願い【３】です。何をする部品かだけ教えてください。'],
    'キ　10秒で終わらない': [
        '画面を出して入力を待っているのか、こちらの写し方が原因なのかを',
        '1本ずつ確かめます。',
        '→ こちらで見ます。'],
    'ク　原文に ＰＲＯＣＥＤＵＲＥ ＤＩＶＩＳＩＯＮ が無い': [
        'この8本はプログラムではなくコピー原文（ＦＺＳＬＩＢ）です。',
        'ＣＯＢＯＬ 857本として数えていますが、実行するものではありません。',
        '→ 問題ではありません。'],
    'ケ　そのほか': ['個別に見ます。'],
}

# 「定義体が無く、コピー原文も無い」ために止まっているもの。
# もとのファイル名を添える（村上様が原文を探せるように）。
TEIGI_NASHI = {
    'B10142PP': 'B10141S1',
    'C10050PB': 'C10040S1／C10050S1／C10050S2',
    'D10040PP': 'D10030S1',
    'SEISAN1S': 'D10030S1',
    'SEISANAS': 'D10030S1',
    'D20510PB': 'CSEKJP／D20500S1',
    'D20530PB': 'D20530S1／D20520S1／D20520S2',
    'D20545PB': 'D20520S3／D20545S1',
    'SHIZI74F': 'FSSIFL2（01レコード名が定義体と別）',
    'F10585PB': 'F10540I1',
}


def kubun(ku, na, r):
    x = re.sub(r'^.*…\s*', '', r)
    # ★ まず「定義体もコピー原文も無い」10本。止まり方（項目名が引けない／
    #    表が無い）は違っても**原因は1つ**なので、同じ区分にまとめる。
    if na in TEIGI_NASHI:
        return ('エ　【ご確認】定義体の無いファイルの中身が分からない',
                '%s　← %s' % (x, TEIGI_NASHI[na]))
    if ku == '_Tobu':
        return 'ア　ＧＯ ＴＯ の飛び先が節の外', x
    if ku == '時間切れ':
        return 'キ　10秒で終わらない', x
    if ku == '変換できない':
        return 'ク　原文に ＰＲＯＣＥＤＵＲＥ ＤＩＶＩＳＩＯＮ が無い', x
    if re.match(r'^READ .*表が無い', x):
        return 'イ　ＲＥＡＤ の先が見つからない', x
    if re.match(r'^(WRITE|REWRITE|START|DELETE) .*表が無い', x):
        return 'ウ　書き先が見つからない', x
    if x.startswith('知らない項目'):
        return 'エ　【ご確認】定義体の無いファイルの中身が分からない', x
    if x.startswith('PERFORM'):
        return 'オ　ＰＥＲＦＯＲＭ 〜 ＴＨＲＵ 〜 の飛び先が無い', x
    if 'XSBSSI' in x:
        return 'カ　【ご確認】外部プログラム ＸＳＢＳＳＩ', x
    if x.startswith('CALL'):
        return 'カ　【ご確認】外部プログラム ＸＳＢＳＳＩ', x
    return 'ケ　そのほか', x


def main():
    t = MOTO.read_text(encoding='utf-8')
    gyo = []
    for ln in t.splitlines()[2:]:
        b = ln.split('\t')
        if len(b) >= 3:
            gyo.append((b[0], b[1], re.sub(r'（原文 \d+行）', '', b[2]).strip()))
    g = collections.defaultdict(list)
    for ku, na, r in gyo:
        k, x = kubun(ku, na, r)
        g[k].append((na, x))

    o = ['ＦＴＳ－ＣＩＭ　実データで857本を動かして止まったところ（全件）',
         '作成 %s' % datetime.date.today().isoformat(), '',
         '　止まったのは %d本です。下に全件を区分ごとに並べました。' % len(gyo),
         '　【ご確認】と書いた区分だけ、村上様のご判断が要ります。',
         '　そのほかは「→ こちらで直します」「→ 問題ではありません」です。', '']
    for k in sorted(g):
        o += ['', '=' * 74, '%s　… %d本' % (k, len(g[k])), '-' * 74]
        o += ['　' + x for x in SETSU.get(k, ['　'])]
        o += ['', '　プログラムと、止まった場所']
        o += ['　　%-10s %s' % (na, x) for na, x in sorted(g[k])]
    SAKI.write_text('\n'.join(o), encoding='utf-8')
    print('%s に書きました（%d本）' % (SAKI, len(gyo)))
    for k in sorted(g):
        print('  %-40s %d' % (k, len(g[k])))


if __name__ == '__main__':
    main()
